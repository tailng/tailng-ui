/* global console, process */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(scriptDirectory, '..');
const exampleRoot = resolve(
  docsRoot,
  'src/app/pages/components/ai/chat/sections/examples/live-chat-demo',
);
const outputPath = resolve(exampleRoot, 'ai-chat-live-demo-code.generated.ts');
const mode = process.argv[2] ?? 'build';

const sourceFiles = [
  { value: 'ts', label: 'TS', language: 'ts', name: 'ai-chat-live-demo.component.ts' },
  { value: 'html', label: 'HTML', language: 'html', name: 'ai-chat-live-demo.component.html' },
  { value: 'css', label: 'CSS', language: 'css', name: 'ai-chat-live-demo.component.css' },
];

const tabs = sourceFiles.map((file) => ({
  value: file.value,
  label: file.label,
  language: file.language,
  title: file.name,
  code: readFileSync(resolve(exampleRoot, file.name), 'utf8'),
}));

const generated = [
  '// Generated by apps/tailng-ui/docs/scripts/example-sources.mjs. Do not edit.',
  "import type { DocsExampleCodeTab } from '../../../../../../../shared/example-panel/docs-example-panel.component';",
  '',
  `export const aiChatLiveDemoCodeTabs: readonly DocsExampleCodeTab[] = Object.freeze(${JSON.stringify(tabs, null, 2)});`,
  '',
].join('\n');

if (mode === 'check') {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    console.error(
      `${relative(process.cwd(), outputPath)} is stale. Run: pnpm run docs:examples:build`,
    );
    process.exitCode = 1;
  } else {
    console.log('documentation example sources are current');
  }
} else if (mode === 'build') {
  writeFileSync(outputPath, generated);
  console.log(`generated ${relative(process.cwd(), outputPath)}`);
} else {
  throw new Error(`Unknown mode: ${mode}`);
}
